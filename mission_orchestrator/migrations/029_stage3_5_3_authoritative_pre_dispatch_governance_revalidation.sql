-- Stage 3.5.3 — Authoritative Pre-Dispatch Governance Revalidation
-- Append-only authoritative pre-dispatch PolicyDecision evidence. ALLOW may grant
-- execution authorization, but this stage still performs no endpoint resolution,
-- health probe, resource assignment, dispatch, target I/O, or actuation.

CREATE TABLE IF NOT EXISTS mission_pre_dispatch_governance_revalidations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    pre_dispatch_revalidation_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    dispatch_eligibility_id VARCHAR(100) NOT NULL,
    revalidation_sequence INT UNSIGNED NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    operation_id VARCHAR(100) NOT NULL,
    static_revalidation_status VARCHAR(80) NOT NULL,
    policy_decision_id VARCHAR(160) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    governance_decision VARCHAR(32) NOT NULL,
    policy_version INT UNSIGNED NOT NULL,
    execution_authorization_status VARCHAR(180) NOT NULL,
    execution_authorized TINYINT(1) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    requested_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_pre_dispatch_revalidation_id (pre_dispatch_revalidation_id),
    UNIQUE KEY uq_pre_dispatch_revalidation_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_pre_dispatch_revalidation_sequence (mission_id, dispatch_eligibility_id, revalidation_sequence),
    KEY idx_pre_dispatch_revalidation_mission (mission_id, plan_version, planned_task_id),
    KEY idx_pre_dispatch_revalidation_dispatch (mission_id, execution_dispatch_id, id),
    CONSTRAINT fk_pre_dispatch_revalidation_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_pre_dispatch_revalidation_dispatch FOREIGN KEY (execution_dispatch_id) REFERENCES mission_execution_dispatch_contracts(execution_dispatch_id),
    CONSTRAINT fk_pre_dispatch_revalidation_eligibility FOREIGN KEY (dispatch_eligibility_id) REFERENCES mission_execution_dispatch_eligibility_gates(dispatch_eligibility_id),
    CONSTRAINT fk_pre_dispatch_revalidation_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_pre_dispatch_revalidation_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_pre_dispatch_revalidation_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
