-- Stage 3.5.1 — Canonical Execution Dispatch Contract & Identity
-- Immutable dispatch-definition store only. This migration does NOT authorize execution,
-- perform dispatch, resolve runtime endpoints, query Governance, or actuate a target.

CREATE TABLE IF NOT EXISTS mission_execution_dispatch_contracts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    delivery_receipt_id VARCHAR(100) NOT NULL,
    delegation_id VARCHAR(100) NOT NULL,
    handoff_envelope_id VARCHAR(100) NOT NULL,
    route_decision_id VARCHAR(100) NOT NULL,
    delegation_authorization_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    dispatch_status VARCHAR(120) NOT NULL,
    target_subsystem VARCHAR(64) NOT NULL,
    target_capability VARCHAR(160) NOT NULL,
    target_capability_version INT UNSIGNED NOT NULL,
    delivery_receipt_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_execution_dispatch_id (execution_dispatch_id),
    UNIQUE KEY uq_execution_dispatch_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_execution_dispatch_task (mission_id, plan_version, planned_task_id),
    KEY idx_execution_dispatch_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_execution_dispatch_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_execution_dispatch_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_execution_dispatch_planned_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT fk_execution_dispatch_delivery FOREIGN KEY (delivery_receipt_id) REFERENCES mission_delegation_deliveries(delivery_receipt_id),
    CONSTRAINT fk_execution_dispatch_delegation FOREIGN KEY (delegation_id) REFERENCES mission_task_delegations(delegation_id),
    CONSTRAINT fk_execution_dispatch_route FOREIGN KEY (route_decision_id) REFERENCES mission_task_route_decisions(route_decision_id),
    CONSTRAINT fk_execution_dispatch_dauth FOREIGN KEY (delegation_authorization_id) REFERENCES mission_delegation_authorizations(delegation_authorization_id),
    CONSTRAINT chk_execution_dispatch_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
