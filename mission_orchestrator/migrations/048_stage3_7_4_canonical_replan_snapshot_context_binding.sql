CREATE TABLE IF NOT EXISTS mission_replan_snapshots (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    replan_snapshot_id VARCHAR(100) NOT NULL,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    replan_trigger_id VARCHAR(100) NOT NULL,
    classification_id VARCHAR(100) NOT NULL,
    eligibility_gate_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    source_plan_version_record_id VARCHAR(100) NOT NULL,
    source_plan_version INT UNSIGNED NOT NULL,
    source_plan_generation INT UNSIGNED NOT NULL,
    target_plan_generation INT UNSIGNED NOT NULL,
    canonical_plan_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    snapshot_status VARCHAR(40) NOT NULL,
    source_adaptation_replan_sha256 CHAR(64) NOT NULL,
    source_classification_sha256 CHAR(64) NOT NULL,
    source_eligibility_sha256 CHAR(64) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    mission_scope_snapshot_id VARCHAR(100) NOT NULL,
    mission_scope_sha256 CHAR(64) NOT NULL,
    governance_binding_snapshot_id VARCHAR(100) NOT NULL,
    governance_binding_version INT UNSIGNED NOT NULL,
    governance_binding_sha256 CHAR(64) NOT NULL,
    task_context_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    bound_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    bound_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_replan_snapshot_id (replan_snapshot_id),
    UNIQUE KEY uq_mission_replan_snapshot_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_replan_snapshot_trigger (replan_trigger_id),
    UNIQUE KEY uq_mission_replan_snapshot_classification (classification_id),
    UNIQUE KEY uq_mission_replan_snapshot_eligibility (eligibility_gate_id),
    UNIQUE KEY uq_mission_replan_snapshot_idempotency (mission_id, idempotency_key),
    KEY idx_mission_replan_snapshots_mission (mission_id, source_plan_version, id),
    KEY idx_mission_replan_snapshots_status (mission_id, snapshot_status),
    CONSTRAINT fk_mission_replan_snapshot_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_replan_snapshot_episode FOREIGN KEY (adaptation_episode_id) REFERENCES mission_adaptation_replan_contracts(adaptation_episode_id),
    CONSTRAINT fk_mission_replan_snapshot_trigger FOREIGN KEY (replan_trigger_id) REFERENCES mission_adaptation_replan_contracts(replan_trigger_id),
    CONSTRAINT fk_mission_replan_snapshot_classification FOREIGN KEY (classification_id) REFERENCES mission_adaptation_trigger_classifications(classification_id),
    CONSTRAINT fk_mission_replan_snapshot_eligibility FOREIGN KEY (eligibility_gate_id) REFERENCES mission_replan_eligibility_governance_gates(eligibility_gate_id),
    CONSTRAINT fk_mission_replan_snapshot_plan FOREIGN KEY (source_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_replan_snapshot_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
