-- Stage 3.5.7 — Execution Result / Evidence / Artifact Capture
-- Captures the authoritative downstream terminal execution result and immutable
-- evidence/artifact references.  Payload bodies remain in the downstream evidence
-- stores; Mission Orchestrator persists only references, digests, metadata, provenance,
-- and the canonical result-capture contract.  This stage does not complete the task or
-- transition Mission state; outcome verification remains Stage 3.5.8 authority.

CREATE TABLE IF NOT EXISTS mission_execution_result_captures (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    result_capture_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    running_projection_id VARCHAR(100) NOT NULL,
    execution_delivery_id VARCHAR(100) NOT NULL,
    execution_attempt_id VARCHAR(100) NOT NULL,
    dispatch_envelope_id VARCHAR(100) NOT NULL,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    execution_state VARCHAR(80) NOT NULL,
    execution_attempt_status VARCHAR(120) NOT NULL,
    completed_at VARCHAR(80) NOT NULL,
    evidence_count INT UNSIGNED NOT NULL,
    evidence_manifest_sha256 CHAR(64) NOT NULL,
    artifact_count INT UNSIGNED NOT NULL,
    artifact_manifest_sha256 CHAR(64) NOT NULL,
    recipient_subsystem_id VARCHAR(64) NOT NULL,
    recipient_capability_id VARCHAR(160) NOT NULL,
    runtime_endpoint VARCHAR(500) NOT NULL,
    runtime_health_sha256 CHAR(64) NOT NULL,
    policy_decision_id VARCHAR(160) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    policy_version INT UNSIGNED NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    captured_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_execution_result_capture_id (result_capture_id),
    UNIQUE KEY uq_execution_result_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_execution_result_attempt (mission_id, execution_attempt_id),
    KEY idx_execution_result_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_execution_result_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_execution_result_running FOREIGN KEY (running_projection_id) REFERENCES mission_execution_running_projections(running_projection_id),
    CONSTRAINT fk_execution_result_delivery FOREIGN KEY (execution_delivery_id) REFERENCES mission_execution_deliveries(execution_delivery_id),
    CONSTRAINT fk_execution_result_attempt FOREIGN KEY (execution_attempt_id) REFERENCES mission_execution_attempts(execution_attempt_id),
    CONSTRAINT fk_execution_result_dispatch FOREIGN KEY (execution_dispatch_id) REFERENCES mission_execution_dispatch_contracts(execution_dispatch_id),
    CONSTRAINT fk_execution_result_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_execution_result_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_execution_result_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
