CREATE TABLE IF NOT EXISTS mission_replan_handoffs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    replan_handoff_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    replan_trigger_id VARCHAR(100) NOT NULL,
    replan_commit_id VARCHAR(100) NOT NULL,
    replan_validation_id VARCHAR(100) NOT NULL,
    predecessor_plan_version_record_id VARCHAR(100) NOT NULL,
    predecessor_plan_version INT UNSIGNED NOT NULL,
    successor_plan_version_record_id VARCHAR(100) NOT NULL,
    successor_plan_version INT UNSIGNED NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    handoff_status VARCHAR(40) NOT NULL,
    source_replan_commit_sha256 CHAR(64) NOT NULL,
    predecessor_plan_sha256 CHAR(64) NOT NULL,
    successor_plan_sha256 CHAR(64) NOT NULL,
    task_disposition_count INT UNSIGNED NOT NULL,
    keep_count INT UNSIGNED NOT NULL,
    drain_count INT UNSIGNED NOT NULL,
    cancel_count INT UNSIGNED NOT NULL,
    supersede_count INT UNSIGNED NOT NULL,
    replace_count INT UNSIGNED NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    handed_off_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    handed_off_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_replan_handoff_id (replan_handoff_id),
    UNIQUE KEY uq_mission_replan_handoff_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_replan_handoff_trigger (replan_trigger_id),
    UNIQUE KEY uq_mission_replan_handoff_commit (replan_commit_id),
    UNIQUE KEY uq_mission_replan_handoff_successor (successor_plan_version_record_id),
    UNIQUE KEY uq_mission_replan_handoff_idempotency (mission_id, idempotency_key),
    KEY idx_mission_replan_handoffs_mission (mission_id, successor_plan_version, id),
    KEY idx_mission_replan_handoffs_status (mission_id, handoff_status),
    CONSTRAINT fk_mission_replan_handoff_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_replan_handoff_commit FOREIGN KEY (replan_commit_id) REFERENCES mission_replan_commits(replan_commit_id),
    CONSTRAINT fk_mission_replan_handoff_predecessor FOREIGN KEY (predecessor_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_mission_replan_handoff_successor FOREIGN KEY (successor_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_replan_handoff_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
