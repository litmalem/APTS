CREATE TABLE IF NOT EXISTS mission_adaptation_replan_contracts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    replan_trigger_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    source_plan_version_record_id VARCHAR(100) NOT NULL,
    source_plan_version INT UNSIGNED NOT NULL,
    source_plan_generation INT UNSIGNED NOT NULL,
    target_plan_generation INT UNSIGNED NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    episode_state VARCHAR(40) NOT NULL,
    trigger_source VARCHAR(40) NOT NULL,
    trigger_code VARCHAR(80) NOT NULL,
    source_event_id VARCHAR(100) NULL,
    source_event_sha256 CHAR(64) NULL,
    evidence_ref_count INT UNSIGNED NOT NULL,
    evidence_refs_json LONGTEXT NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    detected_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    detected_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_adaptation_replan_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_adaptation_replan_trigger (replan_trigger_id),
    UNIQUE KEY uq_mission_adaptation_replan_idempotency (mission_id, idempotency_key),
    KEY idx_mission_adaptation_replan_mission (mission_id, source_plan_version, id),
    CONSTRAINT fk_mission_adaptation_replan_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_adaptation_replan_plan FOREIGN KEY (source_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_adaptation_replan_evidence_json CHECK (json_valid(evidence_refs_json)),
    CONSTRAINT chk_mission_adaptation_replan_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
