CREATE TABLE IF NOT EXISTS mission_adaptation_trigger_classifications (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    classification_id VARCHAR(100) NOT NULL,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    replan_trigger_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    source_plan_version_record_id VARCHAR(100) NOT NULL,
    source_plan_version INT UNSIGNED NOT NULL,
    source_plan_generation INT UNSIGNED NOT NULL,
    canonical_plan_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    classification_status VARCHAR(40) NOT NULL,
    reason_code VARCHAR(80) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    replan_scope_level VARCHAR(40) NOT NULL,
    source_stage VARCHAR(80) NOT NULL,
    source_event_id VARCHAR(100) NULL,
    source_event_sha256 CHAR(64) NULL,
    evidence_ref_count INT UNSIGNED NOT NULL,
    evidence_refs_json LONGTEXT NOT NULL,
    detection_event_id VARCHAR(100) NOT NULL,
    detection_event_sha256 CHAR(64) NOT NULL,
    source_adaptation_replan_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    classified_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    classified_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_adaptation_trigger_classification_id (classification_id),
    UNIQUE KEY uq_mission_adaptation_trigger_classification_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_adaptation_trigger_classification_trigger (replan_trigger_id),
    UNIQUE KEY uq_mission_adaptation_trigger_classification_idempotency (mission_id, idempotency_key),
    KEY idx_mission_adaptation_trigger_classification_mission (mission_id, source_plan_version, id),
    KEY idx_mission_adaptation_trigger_classification_reason (mission_id, reason_code, severity),
    CONSTRAINT fk_mission_adaptation_trigger_classification_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_adaptation_trigger_classification_episode FOREIGN KEY (adaptation_episode_id) REFERENCES mission_adaptation_replan_contracts(adaptation_episode_id),
    CONSTRAINT fk_mission_adaptation_trigger_classification_trigger FOREIGN KEY (replan_trigger_id) REFERENCES mission_adaptation_replan_contracts(replan_trigger_id),
    CONSTRAINT fk_mission_adaptation_trigger_classification_plan FOREIGN KEY (source_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_adaptation_trigger_classification_evidence_json CHECK (json_valid(evidence_refs_json)),
    CONSTRAINT chk_mission_adaptation_trigger_classification_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
