CREATE TABLE IF NOT EXISTS mission_replan_commits (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    replan_commit_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    replan_trigger_id VARCHAR(100) NOT NULL,
    eligibility_gate_id VARCHAR(100) NOT NULL,
    replan_snapshot_id VARCHAR(100) NOT NULL,
    replan_candidate_id VARCHAR(100) NOT NULL,
    replan_validation_id VARCHAR(100) NOT NULL,
    predecessor_plan_version_record_id VARCHAR(100) NOT NULL,
    predecessor_plan_version INT UNSIGNED NOT NULL,
    successor_plan_version_record_id VARCHAR(100) NOT NULL,
    successor_plan_version INT UNSIGNED NOT NULL,
    candidate_plan_generation INT UNSIGNED NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    authorization_operation_id VARCHAR(100) NOT NULL,
    policy_decision_id VARCHAR(100) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    policy_version BIGINT UNSIGNED NOT NULL,
    governance_decision VARCHAR(20) NOT NULL,
    commit_status VARCHAR(50) NOT NULL,
    source_replan_validation_sha256 CHAR(64) NOT NULL,
    source_replan_candidate_sha256 CHAR(64) NOT NULL,
    candidate_payload_sha256 CHAR(64) NOT NULL,
    source_replan_snapshot_sha256 CHAR(64) NOT NULL,
    source_plan_sha256 CHAR(64) NOT NULL,
    successor_plan_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    requested_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    committed_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_replan_commit_id (replan_commit_id),
    UNIQUE KEY uq_mission_replan_commit_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_replan_commit_trigger (replan_trigger_id),
    UNIQUE KEY uq_mission_replan_commit_candidate (replan_candidate_id),
    UNIQUE KEY uq_mission_replan_commit_validation (replan_validation_id),
    UNIQUE KEY uq_mission_replan_commit_successor (successor_plan_version_record_id),
    UNIQUE KEY uq_mission_replan_commit_operation (authorization_operation_id),
    UNIQUE KEY uq_mission_replan_commit_idempotency (mission_id, idempotency_key),
    KEY idx_mission_replan_commits_mission (mission_id, predecessor_plan_version, id),
    KEY idx_mission_replan_commits_status (mission_id, commit_status),
    CONSTRAINT fk_mission_replan_commit_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_replan_commit_eligibility FOREIGN KEY (eligibility_gate_id) REFERENCES mission_replan_eligibility_governance_gates(eligibility_gate_id),
    CONSTRAINT fk_mission_replan_commit_snapshot FOREIGN KEY (replan_snapshot_id) REFERENCES mission_replan_snapshots(replan_snapshot_id),
    CONSTRAINT fk_mission_replan_commit_candidate FOREIGN KEY (replan_candidate_id) REFERENCES mission_replan_candidates(replan_candidate_id),
    CONSTRAINT fk_mission_replan_commit_validation FOREIGN KEY (replan_validation_id) REFERENCES mission_replan_decisions(replan_validation_id),
    CONSTRAINT fk_mission_replan_commit_predecessor FOREIGN KEY (predecessor_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_mission_replan_commit_successor FOREIGN KEY (successor_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_replan_commit_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
