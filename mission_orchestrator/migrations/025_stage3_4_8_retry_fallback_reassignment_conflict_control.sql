-- Stage 3.4.8 — Retry, Fallback, Reassignment & Conflict Control
-- MySQL/MariaDB deployment migration. SQLite acceptance schema is bootstrapped
-- by MissionRepository.ensure_schema().

CREATE TABLE IF NOT EXISTS mission_delegation_recovery_controls (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    recovery_control_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    delivery_receipt_id VARCHAR(100) NOT NULL,
    delegation_id VARCHAR(100) NOT NULL,
    route_decision_id VARCHAR(100) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(160) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    control_sequence INT UNSIGNED NOT NULL,
    control_action VARCHAR(64) NOT NULL,
    control_outcome VARCHAR(120) NOT NULL,
    current_owner_subsystem VARCHAR(64) NOT NULL,
    current_owner_capability VARCHAR(160) NOT NULL,
    current_owner_capability_version INT UNSIGNED NOT NULL,
    proposed_subsystem VARCHAR(64) NULL,
    proposed_capability VARCHAR(160) NULL,
    proposed_capability_version INT UNSIGNED NULL,
    retry_ordinal INT UNSIGNED NULL,
    conflict_status VARCHAR(80) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    requested_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_delegation_recovery_control_id (recovery_control_id),
    UNIQUE KEY uq_delegation_recovery_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_delegation_recovery_sequence (mission_id, delivery_receipt_id, control_sequence),
    KEY idx_delegation_recovery_mission (mission_id, plan_version, planned_task_id, control_sequence),
    CONSTRAINT fk_delegation_recovery_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_delegation_recovery_delivery FOREIGN KEY (delivery_receipt_id) REFERENCES mission_delegation_deliveries(delivery_receipt_id),
    CONSTRAINT fk_delegation_recovery_delegation FOREIGN KEY (delegation_id) REFERENCES mission_task_delegations(delegation_id),
    CONSTRAINT fk_delegation_recovery_route FOREIGN KEY (route_decision_id) REFERENCES mission_task_route_decisions(route_decision_id),
    CONSTRAINT fk_delegation_recovery_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_delegation_recovery_planned_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_delegation_recovery_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
