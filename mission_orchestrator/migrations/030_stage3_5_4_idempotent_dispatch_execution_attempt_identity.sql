-- Stage 3.5.4 — Idempotent Dispatch & Execution Attempt Identity
-- Durable local commit only. No runtime endpoint resolution, target delivery,
-- acknowledgement, execution start, target network I/O, or actuation occurs here.

CREATE TABLE IF NOT EXISTS mission_execution_attempts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    execution_attempt_id VARCHAR(100) NOT NULL,
    dispatch_envelope_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    dispatch_eligibility_id VARCHAR(100) NOT NULL,
    pre_dispatch_revalidation_id VARCHAR(100) NOT NULL,
    attempt_ordinal INT UNSIGNED NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    dispatch_commit_status VARCHAR(100) NOT NULL,
    execution_attempt_status VARCHAR(100) NOT NULL,
    policy_decision_id VARCHAR(160) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    policy_version INT UNSIGNED NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_execution_attempt_id (execution_attempt_id),
    UNIQUE KEY uq_execution_attempt_envelope (dispatch_envelope_id),
    UNIQUE KEY uq_execution_attempt_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_execution_attempt_dispatch (mission_id, execution_dispatch_id),
    UNIQUE KEY uq_execution_attempt_ordinal (mission_id, execution_dispatch_id, attempt_ordinal),
    KEY idx_execution_attempt_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_execution_attempt_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_execution_attempt_dispatch FOREIGN KEY (execution_dispatch_id) REFERENCES mission_execution_dispatch_contracts(execution_dispatch_id),
    CONSTRAINT fk_execution_attempt_eligibility FOREIGN KEY (dispatch_eligibility_id) REFERENCES mission_execution_dispatch_eligibility_gates(dispatch_eligibility_id),
    CONSTRAINT fk_execution_attempt_revalidation FOREIGN KEY (pre_dispatch_revalidation_id) REFERENCES mission_pre_dispatch_governance_revalidations(pre_dispatch_revalidation_id),
    CONSTRAINT fk_execution_attempt_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_execution_attempt_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_execution_attempt_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
