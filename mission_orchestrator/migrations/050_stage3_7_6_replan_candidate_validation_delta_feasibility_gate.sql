CREATE TABLE IF NOT EXISTS mission_replan_decisions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    replan_validation_id VARCHAR(100) NOT NULL,
    replan_candidate_id VARCHAR(100) NOT NULL,
    replan_snapshot_id VARCHAR(100) NOT NULL,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    source_plan_version_record_id VARCHAR(100) NOT NULL,
    source_plan_version INT UNSIGNED NOT NULL,
    candidate_plan_version INT UNSIGNED NOT NULL,
    candidate_plan_generation INT UNSIGNED NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    validation_status VARCHAR(40) NOT NULL,
    feasible TINYINT(1) NOT NULL,
    failed_check_count INT UNSIGNED NOT NULL,
    source_replan_candidate_sha256 CHAR(64) NOT NULL,
    candidate_payload_sha256 CHAR(64) NOT NULL,
    source_replan_snapshot_sha256 CHAR(64) NOT NULL,
    source_plan_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    validated_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    validated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_replan_decision_id (replan_validation_id),
    UNIQUE KEY uq_mission_replan_decision_candidate (replan_candidate_id),
    UNIQUE KEY uq_mission_replan_decision_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_replan_decision_idempotency (mission_id, idempotency_key),
    KEY idx_mission_replan_decisions_mission (mission_id, source_plan_version, id),
    KEY idx_mission_replan_decisions_status (mission_id, validation_status),
    CONSTRAINT fk_mission_replan_decision_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_replan_decision_candidate FOREIGN KEY (replan_candidate_id) REFERENCES mission_replan_candidates(replan_candidate_id),
    CONSTRAINT fk_mission_replan_decision_snapshot FOREIGN KEY (replan_snapshot_id) REFERENCES mission_replan_snapshots(replan_snapshot_id),
    CONSTRAINT fk_mission_replan_decision_episode FOREIGN KEY (adaptation_episode_id) REFERENCES mission_adaptation_replan_contracts(adaptation_episode_id),
    CONSTRAINT fk_mission_replan_decision_plan FOREIGN KEY (source_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_replan_decision_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
