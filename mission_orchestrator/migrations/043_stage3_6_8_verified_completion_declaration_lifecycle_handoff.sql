CREATE TABLE IF NOT EXISTS mission_verified_completion_declarations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    declaration_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    readiness_id VARCHAR(100) NOT NULL,
    evaluation_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    declaration_status VARCHAR(100) NOT NULL,
    readiness_sha256 CHAR(64) NOT NULL,
    evaluation_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    declared_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    declared_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_verified_completion_id (declaration_id),
    UNIQUE KEY uq_mission_verified_completion_idempotency (mission_id, idempotency_key),
    KEY idx_mission_verified_completion_mission (mission_id, plan_version, id),
    CONSTRAINT fk_mission_verified_completion_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_verified_completion_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_mission_verified_completion_readiness FOREIGN KEY (readiness_id) REFERENCES mission_completion_readiness_decisions(readiness_id),
    CONSTRAINT fk_mission_verified_completion_eval FOREIGN KEY (evaluation_id) REFERENCES mission_success_criteria_evaluations(evaluation_id),
    CONSTRAINT chk_mission_verified_completion_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
