CREATE TABLE IF NOT EXISTS mission_outcome_recovery_checkpoints (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    checkpoint_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    checkpoint_version INT UNSIGNED NOT NULL,
    declaration_id VARCHAR(100) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    source_event_count INT UNSIGNED NOT NULL,
    source_event_tip_sha256 CHAR(64) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_outcome_recovery_id (checkpoint_id),
    UNIQUE KEY uq_mission_outcome_recovery_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_mission_outcome_recovery_declaration (mission_id, declaration_id),
    KEY idx_mission_outcome_recovery_mission (mission_id, checkpoint_version, id),
    CONSTRAINT fk_mission_outcome_recovery_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_outcome_recovery_declaration FOREIGN KEY (declaration_id) REFERENCES mission_verified_completion_declarations(declaration_id),
    CONSTRAINT fk_mission_outcome_recovery_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_outcome_recovery_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
