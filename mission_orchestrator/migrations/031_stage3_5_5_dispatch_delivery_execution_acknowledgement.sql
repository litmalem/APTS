-- Stage 3.5.5 — Dispatch Delivery & Execution Acknowledgement
-- Resolves the runtime endpoint for the canonical Stage-3.5.4 xattempt/xenv,
-- probes runtime health, delivers the immutable envelope, and records a durable
-- downstream acknowledgement. Execution is not yet RUNNING and no target actuation
-- is permitted in this stage.

CREATE TABLE IF NOT EXISTS mission_execution_deliveries (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    execution_delivery_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    execution_attempt_id VARCHAR(100) NOT NULL,
    dispatch_envelope_id VARCHAR(100) NOT NULL,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    delivery_status VARCHAR(100) NOT NULL,
    acknowledgement_status VARCHAR(120) NOT NULL,
    execution_attempt_status VARCHAR(120) NOT NULL,
    recipient_subsystem_id VARCHAR(64) NOT NULL,
    recipient_capability_id VARCHAR(160) NOT NULL,
    runtime_endpoint VARCHAR(500) NOT NULL,
    runtime_health_sha256 CHAR(64) NOT NULL,
    acknowledgement_id VARCHAR(160) NOT NULL,
    acknowledgement_sha256 CHAR(64) NOT NULL,
    policy_decision_id VARCHAR(160) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    policy_version INT UNSIGNED NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    delivered_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_execution_delivery_id (execution_delivery_id),
    UNIQUE KEY uq_execution_delivery_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_execution_delivery_attempt (mission_id, execution_attempt_id),
    UNIQUE KEY uq_execution_delivery_envelope (mission_id, dispatch_envelope_id),
    KEY idx_execution_delivery_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_execution_delivery_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_execution_delivery_attempt FOREIGN KEY (execution_attempt_id) REFERENCES mission_execution_attempts(execution_attempt_id),
    CONSTRAINT fk_execution_delivery_dispatch FOREIGN KEY (execution_dispatch_id) REFERENCES mission_execution_dispatch_contracts(execution_dispatch_id),
    CONSTRAINT fk_execution_delivery_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_execution_delivery_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_execution_delivery_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
