CREATE TABLE IF NOT EXISTS mission_replan_eligibility_governance_gates (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    eligibility_gate_id VARCHAR(100) NOT NULL,
    classification_id VARCHAR(100) NOT NULL,
    adaptation_episode_id VARCHAR(100) NOT NULL,
    replan_trigger_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    source_plan_version_record_id VARCHAR(100) NOT NULL,
    source_plan_version INT UNSIGNED NOT NULL,
    source_plan_generation INT UNSIGNED NOT NULL,
    canonical_plan_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    static_eligibility_status VARCHAR(40) NOT NULL,
    eligibility_status VARCHAR(40) NOT NULL,
    replan_eligible TINYINT(1) NOT NULL,
    governance_decision VARCHAR(20) NOT NULL,
    policy_decision_id VARCHAR(100) NOT NULL,
    policy_request_id VARCHAR(100) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    policy_version INT UNSIGNED NOT NULL,
    governance_scope_contract_id VARCHAR(100) NOT NULL,
    governance_scope_version INT UNSIGNED NOT NULL,
    governance_scope_contract_hash CHAR(64) NOT NULL,
    mission_scope_snapshot_id VARCHAR(100) NOT NULL,
    mission_scope_sha256 CHAR(64) NOT NULL,
    governance_binding_snapshot_id VARCHAR(100) NOT NULL,
    governance_binding_version INT UNSIGNED NOT NULL,
    governance_binding_sha256 CHAR(64) NOT NULL,
    source_classification_sha256 CHAR(64) NOT NULL,
    source_adaptation_replan_sha256 CHAR(64) NOT NULL,
    classification_event_id VARCHAR(100) NOT NULL,
    classification_event_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    requested_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    evaluated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_replan_eligibility_id (eligibility_gate_id),
    UNIQUE KEY uq_mission_replan_eligibility_classification (classification_id),
    UNIQUE KEY uq_mission_replan_eligibility_episode (adaptation_episode_id),
    UNIQUE KEY uq_mission_replan_eligibility_trigger (replan_trigger_id),
    UNIQUE KEY uq_mission_replan_eligibility_idempotency (mission_id, idempotency_key),
    KEY idx_mission_replan_eligibility_mission (mission_id, source_plan_version, id),
    KEY idx_mission_replan_eligibility_status (mission_id, eligibility_status, governance_decision),
    CONSTRAINT fk_mission_replan_eligibility_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_replan_eligibility_classification FOREIGN KEY (classification_id) REFERENCES mission_adaptation_trigger_classifications(classification_id),
    CONSTRAINT fk_mission_replan_eligibility_episode FOREIGN KEY (adaptation_episode_id) REFERENCES mission_adaptation_replan_contracts(adaptation_episode_id),
    CONSTRAINT fk_mission_replan_eligibility_trigger FOREIGN KEY (replan_trigger_id) REFERENCES mission_adaptation_replan_contracts(replan_trigger_id),
    CONSTRAINT fk_mission_replan_eligibility_plan FOREIGN KEY (source_plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT chk_mission_replan_eligibility_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
