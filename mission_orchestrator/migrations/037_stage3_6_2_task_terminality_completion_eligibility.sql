-- Stage 3.6.2 — Task Terminality & Completion Eligibility
-- Deterministically evaluates terminality and completion eligibility from the
-- immutable Stage-3.6.1 task outcome identity. This stage does not perform task
-- acceptance, evaluate domain acceptance criteria, commit task completion,
-- transition task/Mission state, release dependencies, recalculate readiness,
-- progress the Plan, contact Governance/runtime, redispatch, or actuate.

CREATE TABLE IF NOT EXISTS mission_task_terminality_eligibility_gates (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    eligibility_gate_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    task_outcome_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    gate_status VARCHAR(80) NOT NULL,
    terminality_confirmed TINYINT(1) NOT NULL,
    terminality_status VARCHAR(80) NOT NULL,
    completion_eligibility_status VARCHAR(120) NOT NULL,
    completion_eligible TINYINT(1) NOT NULL,
    eligibility_reason_code VARCHAR(160) NOT NULL,
    task_outcome_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    evaluated_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    evaluated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_task_terminality_eligibility_id (eligibility_gate_id),
    UNIQUE KEY uq_task_terminality_eligibility_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_task_terminality_eligibility_outcome (mission_id, task_outcome_id),
    UNIQUE KEY uq_task_terminality_eligibility_plan_task (mission_id, plan_version, planned_task_id),
    KEY idx_task_terminality_eligibility_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_task_terminality_eligibility_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_task_terminality_eligibility_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_task_terminality_eligibility_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT fk_task_terminality_eligibility_outcome FOREIGN KEY (task_outcome_id) REFERENCES mission_task_outcomes(task_outcome_id),
    CONSTRAINT chk_task_terminality_eligibility_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
