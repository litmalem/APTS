-- Stage 3.6.1 — Canonical Task Outcome Contract & Identity
-- Materializes an immutable task-outcome identity from the already-verified
-- Stage-3.5 terminal execution trajectory. This stage does not accept/complete
-- the task, release dependencies, recalculate readiness, progress the Plan,
-- complete the Mission, contact Governance/runtime, redispatch, or actuate.

CREATE TABLE IF NOT EXISTS mission_task_outcomes (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    task_outcome_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    execution_attempt_id VARCHAR(100) NOT NULL,
    result_capture_id VARCHAR(100) NOT NULL,
    outcome_propagation_id VARCHAR(100) NOT NULL,
    execution_recovery_checkpoint_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    contract_status VARCHAR(120) NOT NULL,
    execution_state VARCHAR(40) NOT NULL,
    source_task_outcome_status VARCHAR(80) NOT NULL,
    outcome_classification VARCHAR(80) NOT NULL,
    result_capture_sha256 CHAR(64) NOT NULL,
    outcome_propagation_sha256 CHAR(64) NOT NULL,
    execution_recovery_checkpoint_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    created_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_task_outcome_id (task_outcome_id),
    UNIQUE KEY uq_task_outcome_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_task_outcome_plan_task (mission_id, plan_version, planned_task_id),
    UNIQUE KEY uq_task_outcome_propagation (mission_id, outcome_propagation_id),
    UNIQUE KEY uq_task_outcome_recovery (mission_id, execution_recovery_checkpoint_id),
    KEY idx_task_outcome_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_task_outcome_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_task_outcome_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_task_outcome_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT fk_task_outcome_attempt FOREIGN KEY (execution_attempt_id) REFERENCES mission_execution_attempts(execution_attempt_id),
    CONSTRAINT fk_task_outcome_result FOREIGN KEY (result_capture_id) REFERENCES mission_execution_result_captures(result_capture_id),
    CONSTRAINT fk_task_outcome_propagation FOREIGN KEY (outcome_propagation_id) REFERENCES mission_execution_outcome_propagations(outcome_propagation_id),
    CONSTRAINT fk_task_outcome_recovery FOREIGN KEY (execution_recovery_checkpoint_id) REFERENCES mission_execution_recovery_checkpoints(checkpoint_id),
    CONSTRAINT chk_task_outcome_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
