CREATE TABLE IF NOT EXISTS mission_completion_readiness_decisions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    readiness_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    evaluation_id VARCHAR(100) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    readiness_status VARCHAR(100) NOT NULL,
    readiness_result VARCHAR(40) NOT NULL,
    completion_ready TINYINT(1) NOT NULL,
    blocker_count INT UNSIGNED NOT NULL,
    evaluation_sha256 CHAR(64) NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    decided_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    decided_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_mission_completion_readiness_id (readiness_id),
    UNIQUE KEY uq_mission_completion_readiness_idempotency (mission_id, idempotency_key),
    KEY idx_mission_completion_readiness_mission (mission_id, plan_version, id),
    CONSTRAINT fk_mission_completion_readiness_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_mission_completion_readiness_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_mission_completion_readiness_eval FOREIGN KEY (evaluation_id) REFERENCES mission_success_criteria_evaluations(evaluation_id),
    CONSTRAINT chk_mission_completion_readiness_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
