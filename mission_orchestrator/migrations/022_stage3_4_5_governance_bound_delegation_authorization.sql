-- Stage 3.4.5 — Governance-Bound Delegation Authorization
-- Canonical DDL is also embedded in MissionRepository bootstrap for SQLite/MySQL parity.
CREATE TABLE IF NOT EXISTS mission_delegation_authorizations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    delegation_authorization_id TEXT NOT NULL UNIQUE,
    mission_id TEXT NOT NULL,
    route_decision_id TEXT NOT NULL,
    plan_version_record_id TEXT NOT NULL,
    plan_version INTEGER NOT NULL,
    planned_task_id TEXT NOT NULL,
    schema_version TEXT NOT NULL,
    request_sha256 TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    governance_binding_version INTEGER NOT NULL,
    governance_binding_sha256 TEXT NOT NULL,
    policy_decision_id TEXT NOT NULL,
    policy_decision_hash TEXT NOT NULL,
    policy_version INTEGER NOT NULL,
    authorization_status TEXT NOT NULL,
    authorization_granted INTEGER NOT NULL,
    selected_subsystem TEXT NOT NULL,
    selected_capability TEXT NOT NULL,
    canonical_sha256 TEXT NOT NULL,
    canonical_json TEXT NOT NULL,
    source_state_version INTEGER NOT NULL,
    source_version_sha256 TEXT NOT NULL,
    requested_by TEXT NOT NULL,
    reason TEXT NULL,
    created_at TEXT NOT NULL,
    UNIQUE(mission_id, idempotency_key),
    UNIQUE(mission_id, route_decision_id)
);
