-- Stage 3.5.8 — Timeout, Cancellation, Abort & Failure Propagation
-- Adds immutable runtime termination-control acknowledgements and terminal outcome
-- propagation records. Non-success results propagate via canonical Mission lifecycle
-- controls; SUCCEEDED remains task-level verified outcome and does not complete Mission.

CREATE TABLE IF NOT EXISTS mission_execution_termination_controls (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    termination_control_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    running_projection_id VARCHAR(100) NOT NULL,
    execution_delivery_id VARCHAR(100) NOT NULL,
    execution_attempt_id VARCHAR(100) NOT NULL,
    dispatch_envelope_id VARCHAR(100) NOT NULL,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    control_action VARCHAR(40) NOT NULL,
    expected_terminal_state VARCHAR(40) NOT NULL,
    control_status VARCHAR(120) NOT NULL,
    acknowledged_at VARCHAR(80) NOT NULL,
    recipient_subsystem_id VARCHAR(64) NOT NULL,
    recipient_capability_id VARCHAR(160) NOT NULL,
    runtime_endpoint VARCHAR(500) NOT NULL,
    runtime_health_sha256 CHAR(64) NOT NULL,
    acknowledgement_sha256 CHAR(64) NOT NULL,
    policy_decision_id VARCHAR(160) NOT NULL,
    policy_decision_hash CHAR(64) NOT NULL,
    policy_version INT UNSIGNED NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    requested_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_execution_termination_control_id (termination_control_id),
    UNIQUE KEY uq_execution_termination_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_execution_termination_attempt (mission_id, execution_attempt_id),
    KEY idx_execution_termination_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_execution_termination_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_execution_termination_running FOREIGN KEY (running_projection_id) REFERENCES mission_execution_running_projections(running_projection_id),
    CONSTRAINT fk_execution_termination_delivery FOREIGN KEY (execution_delivery_id) REFERENCES mission_execution_deliveries(execution_delivery_id),
    CONSTRAINT fk_execution_termination_attempt FOREIGN KEY (execution_attempt_id) REFERENCES mission_execution_attempts(execution_attempt_id),
    CONSTRAINT fk_execution_termination_dispatch FOREIGN KEY (execution_dispatch_id) REFERENCES mission_execution_dispatch_contracts(execution_dispatch_id),
    CONSTRAINT fk_execution_termination_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_execution_termination_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_execution_termination_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mission_execution_outcome_propagations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    outcome_propagation_id VARCHAR(100) NOT NULL,
    mission_id VARCHAR(80) NOT NULL,
    result_capture_id VARCHAR(100) NOT NULL,
    termination_control_id VARCHAR(100) NULL,
    execution_attempt_id VARCHAR(100) NOT NULL,
    dispatch_envelope_id VARCHAR(100) NOT NULL,
    execution_dispatch_id VARCHAR(100) NOT NULL,
    plan_version_record_id VARCHAR(100) NOT NULL,
    plan_version INT UNSIGNED NOT NULL,
    planned_task_id VARCHAR(100) NOT NULL,
    task_key VARCHAR(160) NOT NULL,
    schema_version VARCHAR(180) NOT NULL,
    request_sha256 CHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    execution_state VARCHAR(40) NOT NULL,
    outcome_classification VARCHAR(80) NOT NULL,
    task_outcome_status VARCHAR(80) NOT NULL,
    propagation_action VARCHAR(80) NOT NULL,
    lifecycle_command VARCHAR(40) NULL,
    lifecycle_command_id VARCHAR(128) NULL,
    transition_id VARCHAR(100) NULL,
    resulting_mission_state VARCHAR(40) NOT NULL,
    resulting_state_version BIGINT UNSIGNED NOT NULL,
    canonical_sha256 CHAR(64) NOT NULL,
    canonical_json LONGTEXT NOT NULL,
    source_state VARCHAR(40) NOT NULL,
    source_state_version BIGINT UNSIGNED NOT NULL,
    source_version_sha256 CHAR(64) NOT NULL,
    propagated_by VARCHAR(128) NOT NULL,
    reason TEXT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_execution_outcome_propagation_id (outcome_propagation_id),
    UNIQUE KEY uq_execution_outcome_idempotency (mission_id, idempotency_key),
    UNIQUE KEY uq_execution_outcome_result (mission_id, result_capture_id),
    KEY idx_execution_outcome_mission (mission_id, plan_version, planned_task_id),
    CONSTRAINT fk_execution_outcome_mission FOREIGN KEY (mission_id) REFERENCES global_missions(mission_id),
    CONSTRAINT fk_execution_outcome_result FOREIGN KEY (result_capture_id) REFERENCES mission_execution_result_captures(result_capture_id),
    CONSTRAINT fk_execution_outcome_termination FOREIGN KEY (termination_control_id) REFERENCES mission_execution_termination_controls(termination_control_id),
    CONSTRAINT fk_execution_outcome_attempt FOREIGN KEY (execution_attempt_id) REFERENCES mission_execution_attempts(execution_attempt_id),
    CONSTRAINT fk_execution_outcome_dispatch FOREIGN KEY (execution_dispatch_id) REFERENCES mission_execution_dispatch_contracts(execution_dispatch_id),
    CONSTRAINT fk_execution_outcome_plan FOREIGN KEY (plan_version_record_id) REFERENCES mission_plan_versions(plan_version_record_id),
    CONSTRAINT fk_execution_outcome_task FOREIGN KEY (planned_task_id) REFERENCES mission_planned_tasks(planned_task_id),
    CONSTRAINT chk_execution_outcome_json CHECK (json_valid(canonical_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
